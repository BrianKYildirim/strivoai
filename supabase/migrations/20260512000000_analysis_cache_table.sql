-- Phase 29 · 29-01 · CACHE-01 / CACHE-11 / NFR-01 — analysis_cache substrate.
--
-- Purpose: Ship the public.analysis_cache table, its UNIQUE btree index on
-- cache_key, and the user-scoped SELECT-only RLS policy. Phase 29 ships
-- substrate only — no feature in this plan reads or writes the table at
-- runtime. Phases 37-40 SELECT through this RLS, and the Phase 29-06 merit
-- gateway precheck callback INSERTs via the service role.
--
-- REQ-IDs: CACHE-01 (table shape + UNIQUE + RLS), CACHE-11 (user-scoped
--          lookups via RLS), NFR-01 (idempotent migration; re-run safe).
--
-- Style precedent:
--   20260414000000_merit_ledger_foundation.sql   (CREATE TABLE + ENABLE RLS + SELECT-own policy)
--   20260420000000_mig_02_analysis_results_readonly.sql (DROP POLICY IF EXISTS + CREATE POLICY shape)
--   20260422000000_phase_24_topup.sql            (UNIQUE INDEX IF NOT EXISTS + DO $$ verification block)
--
-- CRITICAL: Do NOT add any INSERT/UPDATE/DELETE policy. Service role
-- (getServiceClient()) bypasses RLS automatically, which is the ONLY
-- legitimate write path. Adding a permissive write policy here is the
-- SEC-06 anti-pattern.
--
-- CRITICAL: Defense-in-depth on top of D-01 (user_id is baked into the
-- SHA-256 cache_key input by cache-fingerprint.ts, so cross-user keys are
-- structurally impossible). RLS predicate is `auth.uid() = user_id`
-- (NEVER `auth.jwt() ->> 'sub'`).
--
-- Rollback: forward-only per NFR-01. This migration contains zero
-- destructive table-drop or index-drop statements. If rollback is ever
-- required, ship a new additive migration with explicit ON CONFLICT
-- semantics; do not edit this file post-deploy.
--
-- Re-runnability: every DDL statement is guarded
--   (CREATE TABLE IF NOT EXISTS, CREATE [UNIQUE] INDEX IF NOT EXISTS,
--    ALTER TABLE ... ENABLE ROW LEVEL SECURITY is itself idempotent,
--    DROP POLICY IF EXISTS + CREATE POLICY). A second
--   `.\scripts\deploy-staging.ps1` is a no-op.

-- ─────────────────────────────────────────────────────────────────────────────
-- 1. CREATE TABLE — CACHE-01 column contract (per 29-RESEARCH.md §Pattern 1
--    and 29-CONTEXT.md D-01).
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.analysis_cache (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  cache_key      text NOT NULL,
  feature        text NOT NULL,
  tier           text NOT NULL
                   CHECK (tier IN ('free','pro','elite')),
  variant        text NULL,
  user_id        uuid NOT NULL
                   REFERENCES public.profiles(id) ON DELETE CASCADE,
  raw_response   jsonb NOT NULL,
  created_at     timestamptz NOT NULL DEFAULT now(),
  last_hit_at    timestamptz NOT NULL DEFAULT now(),
  hit_count      integer NOT NULL DEFAULT 1
                   CHECK (hit_count > 0)
);

-- ─────────────────────────────────────────────────────────────────────────────
-- 2. Indexes
--    (a) D-02 — single UNIQUE btree on cache_key. No composite. Single
--        hash lookup meets NFR-02 (<100ms p95).
--    (b) Supporting analytics index per RESEARCH §Pattern 1 — cheap on a
--        slow-growing table; covers per-user, per-feature dashboards.
-- ─────────────────────────────────────────────────────────────────────────────
CREATE UNIQUE INDEX IF NOT EXISTS analysis_cache_key_unique
  ON public.analysis_cache (cache_key);

CREATE INDEX IF NOT EXISTS analysis_cache_user_feature_created_idx
  ON public.analysis_cache (user_id, feature, created_at DESC);

-- ─────────────────────────────────────────────────────────────────────────────
-- 3. ENABLE ROW LEVEL SECURITY
-- ─────────────────────────────────────────────────────────────────────────────
ALTER TABLE public.analysis_cache ENABLE ROW LEVEL SECURITY;

-- ─────────────────────────────────────────────────────────────────────────────
-- 4. SELECT-own policy (D-03 / CACHE-11)
--    NO INSERT/UPDATE/DELETE policy — service role bypasses RLS for all
--    writes via getServiceClient(). Adding a permissive write policy here
--    is the SEC-06 anti-pattern.
-- ─────────────────────────────────────────────────────────────────────────────
DROP POLICY IF EXISTS analysis_cache_select_own ON public.analysis_cache;
CREATE POLICY analysis_cache_select_own
  ON public.analysis_cache
  FOR SELECT
  TO authenticated
  USING (auth.uid() = user_id);

-- ─────────────────────────────────────────────────────────────────────────────
-- 5. Documentation comments (visible on `\d+ analysis_cache`).
--    Future readers should learn the CACHE-01 ownership + BUDGET-03
--    truncation-before-hash convention without grepping plan files.
-- ─────────────────────────────────────────────────────────────────────────────
COMMENT ON TABLE public.analysis_cache IS
  'Phase 29 CACHE-01: shared response cache substrate for Phases 37-40. Service-role writes only (RLS-bypassing). authenticated SELECTs are RLS-scoped to auth.uid() = user_id (CACHE-11). Single UNIQUE btree on cache_key.';
COMMENT ON COLUMN public.analysis_cache.cache_key IS
  'SHA-256 hex of (user_id || feature || tier || variant || BUDGET-03-truncated input). user_id participates in the hash so cross-user collisions are structurally impossible (defense in depth atop RLS). D-01.';
COMMENT ON COLUMN public.analysis_cache.feature IS
  'Feature identifier (e.g., resume-analysis, career-compass, linkedin-grader). Free-form text; no FK on purpose — features are versioned in code, not in a lookup table.';
COMMENT ON COLUMN public.analysis_cache.tier IS
  'Tier at write time. CHECK constraint matches the canonical free/pro/elite enum used by usage-checker.ts.';
COMMENT ON COLUMN public.analysis_cache.variant IS
  'Optional sub-feature variant (e.g., recruiting-lens criteria pass). NULL when not applicable.';
COMMENT ON COLUMN public.analysis_cache.user_id IS
  'Cache owner. RLS predicate `auth.uid() = user_id` enforces user-scoped reads (CACHE-11). ON DELETE CASCADE so account deletion vacates the cache atomically.';
COMMENT ON COLUMN public.analysis_cache.raw_response IS
  'Verbatim model response payload. jsonb (not json) for indexable/queryable storage and per-key extraction in dashboards. Treat as opaque at the application layer.';
COMMENT ON COLUMN public.analysis_cache.last_hit_at IS
  'Updated by the merit-gateway precheck on cache hit (Phase 29-06). Drives LRU-style cache analytics.';
COMMENT ON COLUMN public.analysis_cache.hit_count IS
  'Incremented on cache hit. CHECK > 0 enforces invariant: a row exists ⇒ it has been hit at least once (the initial write counts).';

-- ─────────────────────────────────────────────────────────────────────────────
-- 6. Verification block (closes 29-RESEARCH.md Pitfall 5).
--    Mirrors the 20260422000000_phase_24_topup.sql:167-196 style verbatim.
--    Any missing artifact raises an exception and rolls back the migration.
-- ─────────────────────────────────────────────────────────────────────────────
DO $$
DECLARE
  rls_enabled   boolean;
  policy_qual   text;
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.tables
    WHERE table_schema = 'public'
      AND table_name   = 'analysis_cache'
  ) THEN
    RAISE EXCEPTION 'Phase 29 CACHE-01 verification failed: public.analysis_cache table missing';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name   = 'analysis_cache'
      AND column_name  = 'cache_key'
  ) THEN
    RAISE EXCEPTION 'Phase 29 CACHE-01 verification failed: analysis_cache.cache_key column missing';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_indexes
    WHERE schemaname = 'public'
      AND indexname  = 'analysis_cache_key_unique'
  ) THEN
    RAISE EXCEPTION 'Phase 29 CACHE-01 verification failed: analysis_cache_key_unique index missing';
  END IF;

  SELECT relrowsecurity INTO rls_enabled
    FROM pg_class
    WHERE relname     = 'analysis_cache'
      AND relnamespace = 'public'::regnamespace;

  IF rls_enabled IS DISTINCT FROM TRUE THEN
    RAISE EXCEPTION 'Phase 29 CACHE-11 verification failed: row-level security NOT enabled on analysis_cache';
  END IF;

  SELECT qual INTO policy_qual
    FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename  = 'analysis_cache'
      AND policyname = 'analysis_cache_select_own';

  IF policy_qual IS NULL THEN
    RAISE EXCEPTION 'Phase 29 CACHE-11 verification failed: analysis_cache_select_own policy missing';
  END IF;

  IF position('auth.uid() = user_id' in policy_qual) = 0 THEN
    RAISE EXCEPTION
      'Phase 29 CACHE-11 verification failed: analysis_cache_select_own policy qual does not match auth.uid() = user_id (got: %)',
      policy_qual;
  END IF;

  RAISE NOTICE 'Phase 29 CACHE-01 / CACHE-11 / NFR-01 verification passed';
END $$;
